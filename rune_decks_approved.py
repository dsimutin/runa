def get_deck_meaning(rune_key: str, deck: str = "light", reversed_position: bool = False) -> dict:
    deck = deck if deck in DECKS else "light"
    data = RUNE_DECKS.get(rune_key, {}).get(deck)
    if not data:
        return {
            "text": "Значение этой руны ещё не добавлено в новую библиотеку.",
            "advice": "Проверь библиотеку трактовок.",
            "position": "перевёрнутое значение" if reversed_position else "прямое значение",
        }
    return {
        "text": data["reversed" if reversed_position else "upright"],
        "advice": data["advice_reversed" if reversed_position else "advice_upright"],
        "position": "перевёрнутое значение" if reversed_position else "прямое значение",
    }


def validate_deck_library() -> tuple[bool, list[str]]:
    expected = {"fehu", "uruz", "thurisaz", "ansuz", "raido", "kenaz", "gebo", "wunjo", "hagalaz", "nauthiz", "isa", "jera", "eihwaz", "perthro", "algiz", "sowilo", "tiwaz", "berkano", "ehwaz", "mannaz", "laguz", "ingwaz", "dagaz", "othala", "wyrd"}
    errors: list[str] = []
    missing = expected - set(RUNE_DECKS)
    extra = set(RUNE_DECKS) - expected
    if missing:
        errors.append("missing runes: " + ", ".join(sorted(missing)))
    if extra:
        errors.append("extra runes: " + ", ".join(sorted(extra)))
    for rune_key in sorted(expected & set(RUNE_DECKS)):
        for deck in DECKS:
            data = RUNE_DECKS[rune_key].get(deck)
            if not data:
                errors.append(f"{rune_key}.{deck}: missing deck")
                continue
            for field in ("upright", "reversed", "advice_upright", "advice_reversed"):
                if not data.get(field):
                    errors.append(f"{rune_key}.{deck}.{field}: empty")
    return not errors, errors
