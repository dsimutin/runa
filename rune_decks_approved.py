def get_deck_meaning(rune_key: str, deck: str = "light", reversed_position: bool = False) -> dict:
    deck = deck if deck in DECKS else "light"
    data = RUNE_DECKS.get(rune_key, {}).get(deck)
    if not data:
        return {
            "text": "Значение этой руны ещё не добавлено в новую библиотеку.",
            "advice": "Проверьте библиотеку трактовок.",
            "position": "перевёрнутое значение" if reversed_position else "прямое значение",
        }
    return {
        "text": data["reversed" if reversed_position else "upright"],
        "advice": data["advice_reversed" if reversed_position else "advice_upright"],
        "position": "перевёрнутое значение" if reversed_position else "прямое значение",
    }
