def detect_question_topic(question: str) -> str:
    q = question.lower()
    scores = {}
    for topic, keywords in QUESTION_TOPICS.items():
        score = sum(1 for keyword in keywords if keyword in q)
        if score:
            scores[topic] = score
    if not scores:
        return "general"
    return max(scores, key=scores.get)


def category_for(rune: Dict[str, Any]) -> str:
    return RUNE_CATEGORIES.get(rune.get("key", ""), "general")


def pick(mapping: Dict[str, Dict[str, List[str]]], category: str, palette: str) -> str | None:
    values = mapping.get(category, {}).get(palette)
    return random.choice(values) if values else None


def build_dynamic_summary(s_cat: str, o_cat: str, a_cat: str, palette: str, question: str) -> List[str]:
    topic = detect_question_topic(question)
    parts: List[str] = [TOPIC_FRAMES.get(topic, TOPIC_FRAMES["general"])[palette]]

    obstacle_text = pick(OBSTACLE_MECHANISMS, o_cat, palette)
    if obstacle_text:
        parts.append(obstacle_text)

    advice_text = pick(ADVICE_DIRECTIONS, a_cat, palette)
    if advice_text:
        parts.append(advice_text)

    if s_cat in {"movement", "flow", "transition"} and o_cat in {"pause", "constraint"}:
        parts.append(random.choice(CONTRADICTION_PATTERNS[palette]))
    elif s_cat in {"energy", "force"} and o_cat in {"unknown", "self", "boundary"}:
        parts.append(random.choice(CONTRADICTION_PATTERNS[palette]))

    if random.random() > 0.35:
        parts.append(random.choice(HIDDEN_PATTERNS[palette]))

    parts.append(random.choice(FINAL_ENDINGS[palette]))
    return parts


def generate_rasklad(runes: List[Dict[str, Any]], question: str, palette: str, name: str = "") -> str:
    if palette not in {"light", "dark"}:
        palette = "light"

    situation, obstacle, advice = runes
    i1 = get_interpretation(situation["key"], palette, situation)
    i2 = get_interpretation(obstacle["key"], palette, obstacle)
    i3 = get_interpretation(advice["key"], palette, advice)

    s_cat = category_for(situation)
    o_cat = category_for(obstacle)
    a_cat = category_for(advice)
    summary_parts = build_dynamic_summary(s_cat, o_cat, a_cat, palette, question)

    intro = f"🔮 {name}, твой расклад" if name else "🔮 Твой расклад"
    summary_text = "\n\n".join(summary_parts)

    return (
        f"{intro}\n"
        f"Вопрос: {question}\n\n"
        f"1️⃣ Ситуация — {situation['name']}\n"
        f"{i1['situation']}\n\n"
        f"2️⃣ Препятствие — {obstacle['name']}\n"
        f"{i2['obstacle']}\n\n"
        f"3️⃣ Вектор — {advice['name']}\n"
        f"{i3['advice']}\n\n"
        f"Итог\n"
        f"{summary_text}"
    )
