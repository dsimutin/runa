EXPANDED_INTERPRETATIONS = {
    key: {"light": _block(key, "light"), "dark": _block(key, "dark")}
    for key in THEMES
}


def get_expanded(rune_key: str, palette: str) -> dict:
    return EXPANDED_INTERPRETATIONS.get(rune_key, {}).get(palette, {})


def get_topic_text(rune_key: str, palette: str, topic: str, field: str, fallback: str = "") -> str:
    data = get_expanded(rune_key, palette)
    return data.get("topics", {}).get(topic, {}).get(field) or fallback


def get_variant(rune_key: str, palette: str, field: str, index: int, fallback: str = "") -> str:
    variants = get_expanded(rune_key, palette).get(field, [])
    if variants:
        return variants[index % len(variants)]
    return fallback
