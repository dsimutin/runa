# Fallback вопросы если руна не найдена
FALLBACK_QUESTIONS: list[str] = [
    "Где ты сейчас не честен с собой — даже в мелочах?",
    "Что ты продолжаешь терпеть, хотя давно знаешь, что это надо менять?",
    "Чего ты на самом деле хочешь — без оглядки на то, что «правильно»?",
]


def question_for_rune(rune_key: str, week: int) -> str:
    """Get a reflection question for a specific rune, rotating by week."""
    questions = RUNE_QUESTIONS.get(rune_key, FALLBACK_QUESTIONS)
    return questions[week % len(questions)]


def rune_of_week(runes: list, week: int) -> dict:
    """Pick a deterministic rune for the week based on week number."""
    # Use hash for better distribution than simple modulo
    h = int(hashlib.sha256(str(week).encode()).hexdigest()[:8], 16)
    return runes[h % len(runes)]


def question_of_week() -> str:
    """Legacy: return a generic weekly question by ISO week number."""
    week = date.today().isocalendar()[1]
    all_questions = [q for qs in RUNE_QUESTIONS.values() for q in qs]
    return all_questions[week % len(all_questions)]
