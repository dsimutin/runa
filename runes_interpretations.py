def get_interpretation(rune_key: str, palette: str, fallback: dict) -> dict:
    """Return palette-aware interpretation with fallback to original rune data."""
    custom = RUNE_INTERPRETATIONS.get(rune_key, {}).get(palette, {})
    return {
        "short_desc": custom.get("short_desc", fallback.get("short_desc", "")),
        "answer_yes": custom.get("answer_yes", fallback.get("answer_yes", "")),
        "answer_no": custom.get("answer_no", fallback.get("answer_no", "")),
        "situation": custom.get("situation", fallback.get("meaning_situation", "")),
        "obstacle": custom.get("obstacle", fallback.get("meaning_obstacle", "")),
        "advice": custom.get("advice", fallback.get("meaning_advice", "")),
    }
